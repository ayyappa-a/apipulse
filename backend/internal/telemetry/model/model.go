// Package model defines the canonical APIPulse telemetry data model.
//
// APIPulse receives telemetry from four distinct sources that must remain
// distinguishable throughout the system. These sources are NEVER conflated:
//
//   - CUSTOMER_OTEL:      Asynchronous OpenTelemetry spans from customer applications
//   - SYNTHETIC_PROBE:    Controlled outbound probes from APIPulse edge agents
//   - VENDOR_STATUS:      Scraped vendor-declared component status
//   - APIPULSE_ASSESSMENT: Computed assessments from the Health Intelligence Engine
//
// IMPORTANT PRIVACY BOUNDARY:
// APIPulse is an observability system, not a payload inspection system.
// No request bodies, response bodies, authentication tokens, PII, or
// payment information are ingested or stored at any point.
package model

import (
	"time"

	"github.com/google/uuid"
)

// TelemetrySource identifies the origin of a telemetry observation.
// This field must always be set and must never be omitted.
type TelemetrySource string

const (
	// SourceCustomerOTEL represents asynchronous OpenTelemetry telemetry
	// emitted by customer application code (e.g. CodeBegun backend).
	// APIPulse is NOT in the production request path for this traffic.
	SourceCustomerOTEL TelemetrySource = "CUSTOMER_OTEL"

	// SourceSyntheticProbe represents observations from APIPulse-controlled
	// outbound probes to third-party dependencies.
	SourceSyntheticProbe TelemetrySource = "SYNTHETIC_PROBE"

	// SourceVendorStatus represents the vendor's own public status declaration
	// scraped from their status page APIs.
	SourceVendorStatus TelemetrySource = "VENDOR_STATUS"

	// SourceAPIPulseAssessment represents computed assessments generated by
	// the APIPulse Health Intelligence Engine by correlating all other sources.
	SourceAPIPulseAssessment TelemetrySource = "APIPULSE_ASSESSMENT"
)

// ObservationStatus represents the result classification of a telemetry observation.
type ObservationStatus string

const (
	StatusOK       ObservationStatus = "ok"
	StatusError    ObservationStatus = "error"
	StatusTimeout  ObservationStatus = "timeout"
	StatusDegraded ObservationStatus = "degraded"
	StatusUnknown  ObservationStatus = "unknown"
)

// ErrorType classifies the error category when Status != ok.
type ErrorType string

const (
	ErrorTypeNone              ErrorType = ""
	ErrorTypeTimeout           ErrorType = "timeout"
	ErrorTypeConnection        ErrorType = "connection"
	ErrorTypeDNS               ErrorType = "dns"
	ErrorTypeTLS               ErrorType = "tls"
	ErrorTypeHTTP4xx           ErrorType = "http_4xx"
	ErrorTypeHTTP5xx           ErrorType = "http_5xx"
	ErrorTypeValidation        ErrorType = "validation"
	ErrorTypeUnknown           ErrorType = "unknown"

	// Canonical Phase 3A Error Classifications
	ErrorTypeDNSFailure        ErrorType = "dns_failure"
	ErrorTypeTCPFailure        ErrorType = "tcp_failure"
	ErrorTypeTLSFailure        ErrorType = "tls_failure"
	ErrorTypeRateLimited       ErrorType = "rate_limited"
	ErrorTypeValidationFailure ErrorType = "validation_failure"
	ErrorTypeNetworkError      ErrorType = "network_error"
)

// DependencyObservation is the normalized internal model for a single
// observation of a third-party dependency from the customer's perspective.
//
// This model is populated from CUSTOMER_OTEL telemetry spans after
// normalization and PII scrubbing. It represents what the customer's
// application actually experienced when calling a dependency.
//
// PRIVACY CONTRACT:
//   - No request or response bodies
//   - No authorization headers or tokens
//   - No payment data, PII, or customer-identifiable fields
//   - No arbitrary query parameters
//   - TraceID is optional and only stored when explicitly permitted
type DependencyObservation struct {
	// ID is the APIPulse-assigned stable UUID for this observation.
	ID uuid.UUID `json:"id" db:"id"`

	// Timestamp is the UTC wall-clock time of the observation start.
	Timestamp time.Time `json:"timestamp" db:"timestamp"`

	// ServiceName is the name of the reporting service (e.g. "codebegun-checkout").
	ServiceName string `json:"service_name" db:"service_name"`

	// DependencyName is the normalized name of the third-party dependency
	// (e.g. "stripe", "sendgrid", "twilio").
	DependencyName string `json:"dependency_name" db:"dependency_name"`

	// Operation is the high-cardinality-safe operation label
	// (e.g. "POST /v1/charges", "GET /v3/mail/send").
	// Must not contain user IDs, trace IDs, or dynamic path segments.
	Operation string `json:"operation" db:"operation"`

	// Region is the AWS/GCP/Azure region where the observation originated
	// (e.g. "us-east-1", "eu-west-1").
	Region string `json:"region" db:"region"`

	// Source identifies the telemetry origin. Always CUSTOMER_OTEL for this model.
	Source TelemetrySource `json:"source" db:"source"`

	// DurationMS is the total observed duration in milliseconds.
	DurationMS float64 `json:"duration_ms" db:"duration_ms"`

	// Status is the normalized outcome of the operation.
	Status ObservationStatus `json:"status" db:"status"`

	// StatusCode is the HTTP response status code (0 if not applicable).
	StatusCode int `json:"status_code" db:"status_code"`

	// ErrorType classifies the failure mode if Status != ok.
	ErrorType ErrorType `json:"error_type" db:"error_type"`

	// TraceID is an optional correlation handle.
	// Only stored if the ingestion pipeline is explicitly configured to retain it.
	// Must never be used as a high-cardinality label.
	TraceID string `json:"trace_id,omitempty" db:"trace_id"`

	// Environment distinguishes telemetry environments (e.g. "production", "staging").
	Environment string `json:"environment" db:"environment"`

	// IngestedAt is the UTC time APIPulse received this observation.
	IngestedAt time.Time `json:"ingested_at" db:"ingested_at"`
}

// ProbeObservation is the normalized internal model for a single
// synthetic probe result from an APIPulse edge agent.
//
// The probe measures the raw TCP/TLS/HTTP waterfall to a third-party dependency
// endpoint from a specific geographic region. It contains no customer payloads.
type ProbeObservation struct {
	// ID is the APIPulse-assigned stable UUID for this probe result.
	ID uuid.UUID `json:"id" db:"id"`

	// ProbeID is the ID of the probe configuration that triggered this observation.
	ProbeID uuid.UUID `json:"probe_id" db:"probe_id"`

	// DependencyID is the ID of the dependency being probed.
	DependencyID uuid.UUID `json:"dependency_id" db:"dependency_id"`

	// Region is the APIPulse edge region that performed the probe
	// (e.g. "us-east-1", "eu-central-1").
	Region string `json:"region" db:"region"`

	// Timestamp is the UTC time the probe was initiated.
	Timestamp time.Time `json:"timestamp" db:"timestamp"`

	// Source is always SYNTHETIC_PROBE for this model.
	Source TelemetrySource `json:"source" db:"source"`

	// Success indicates whether the probe completed without error.
	Success bool `json:"success" db:"success"`

	// HTTPStatusCode is the HTTP response code returned by the target (0 if connection failed).
	HTTPStatusCode int `json:"http_status_code" db:"http_status_code"`

	// Timing breakdown — all durations in milliseconds.

	// DNSDurationMS is the time to resolve the DNS record.
	DNSDurationMS float64 `json:"dns_duration_ms" db:"dns_duration_ms"`

	// TCPDurationMS is the time to complete the TCP three-way handshake.
	TCPDurationMS float64 `json:"tcp_duration_ms" db:"tcp_duration_ms"`

	// TLSDurationMS is the time to complete the TLS handshake.
	TLSDurationMS float64 `json:"tls_duration_ms" db:"tls_duration_ms"`

	// TTFBDurationMS is the Time-To-First-Byte from the server.
	TTFBDurationMS float64 `json:"ttfb_duration_ms" db:"ttfb_duration_ms"`

	// TransferDurationMS is the body transfer duration after TTFB.
	TransferDurationMS float64 `json:"transfer_duration_ms" db:"transfer_duration_ms"`

	// TotalDurationMS is the end-to-end wall-clock duration of the probe.
	TotalDurationMS float64 `json:"total_duration_ms" db:"total_duration_ms"`

	// ReusedConnection indicates whether this probe reused an existing keep-alive connection.
	// When true, DNS/TCP/TLS durations of 0ms accurately represent reuse rather than zero latency.
	ReusedConnection bool `json:"reused_connection" db:"reused_connection"`

	// ErrorType classifies the failure if Success == false.
	ErrorType ErrorType `json:"error_type" db:"error_type"`

	// NetworkError contains a sanitized (non-PII) error description.
	NetworkError string `json:"network_error,omitempty" db:"network_error"`

	// Timeout indicates the probe was terminated due to a deadline exceedance.
	Timeout bool `json:"timeout" db:"timeout"`

	// ResponseValidationResult is an optional structured result from
	// probe-level response validation (e.g. expected JSON field present).
	ResponseValidationResult string `json:"response_validation_result,omitempty" db:"response_validation_result"`

	// IngestedAt is the UTC time APIPulse received this probe result.
	IngestedAt time.Time `json:"ingested_at" db:"ingested_at"`
}

// VendorStatusObservation represents a scraped vendor status page entry.
type VendorStatusObservation struct {
	ID           uuid.UUID       `json:"id" db:"id"`
	VendorID     uuid.UUID       `json:"vendor_id" db:"vendor_id"`
	Timestamp    time.Time       `json:"timestamp" db:"timestamp"`
	Source       TelemetrySource `json:"source" db:"source"`
	Component    string          `json:"component" db:"component"`
	DeclaredStatus string        `json:"declared_status" db:"declared_status"`
	StatusURL    string          `json:"status_url" db:"status_url"`
	RawMessage   string          `json:"raw_message,omitempty" db:"raw_message"`
	IngestedAt   time.Time       `json:"ingested_at" db:"ingested_at"`
}

// Validate checks that a DependencyObservation meets the ingestion contract.
// Returns a non-nil error if any required field is missing or invalid.
func (o *DependencyObservation) Validate() error {
	return validateDependencyObservation(o)
}

// Validate checks that a ProbeObservation meets the ingestion contract.
func (o *ProbeObservation) Validate() error {
	return validateProbeObservation(o)
}
